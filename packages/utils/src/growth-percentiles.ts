// ── Math helpers ───────────────────────────────────────────────────────────

/**
 * Rational approximation of the standard normal CDF Φ(z).
 * Abramowitz & Stegun 26.2.17, max |error| < 7.5×10⁻⁸.
 */
function normalCDF(z: number): number {
  const t = 1 / (1 + 0.2316419 * Math.abs(z));
  const poly =
    t * (0.319381530 +
    t * (-0.356563782 +
    t * (1.781477937 +
    t * (-1.821255978 +
    t *  1.330274429))));
  const phi = 1 - (1 / Math.sqrt(2 * Math.PI)) * Math.exp(-0.5 * z * z) * poly;
  return z >= 0 ? phi : 1 - phi;
}

/**
 * Look up (and linearly interpolate) the LMS triplet for a fractional age.
 * Returns null when age is outside the table's range (0–60 months for WHO 2006).
 */
function lookupLMS(table: LMS[], ageMonths: number): LMS | null {
  const maxIdx = table.length - 1;
  if (ageMonths < 0 || ageMonths > maxIdx) return null;

  const lo = Math.floor(ageMonths);
  const hi = Math.min(lo + 1, maxIdx);
  const frac = ageMonths - lo;

  if (frac === 0 || lo === hi) return table[lo];

  // Linear interpolation between whole-month entries.
  return table[lo].map((v, i) => v + frac * (table[hi][i] - v)) as LMS;
}

/**
 * Calculate WHO z-score using the LMS method.
 *   Z = ((X/M)^L - 1) / (L × S)   (L ≠ 0)
 *   Z = ln(X/M) / S                 (L = 0)
 * Per WHO guidelines, extreme z-scores (|Z| > 3) use the extended-deviation
 * formula to avoid distortion at the tails — clamped to [-5, +5].
 */
function lmsZScore(measurement: number, lms: LMS): number {
  const [L, M, S] = lms;
  let z: number;

  if (Math.abs(L) < 1e-10) {
    z = Math.log(measurement / M) / S;
  } else {
    z = (Math.pow(measurement / M, L) - 1) / (L * S);
  }

  // WHO extended z-score for extreme values (beyond ±3 SD).
  if (Math.abs(z) > 3) {
    const sd3 = M * Math.pow(1 + L * S * 3, 1 / L);
    const sd2 = M * Math.pow(1 + L * S * 2, 1 / L);
    const sdDir = z > 0 ? sd3 - sd2 : sd2 - M * Math.pow(1 + L * S * (-2), 1 / L);
    z = z > 0
      ? 3 + (measurement - sd3) / sdDir
      : -3 + (measurement - M * Math.pow(1 + L * S * (-3), 1 / L)) / sdDir;
  }

  return Math.max(-5, Math.min(5, z));
}

function classifyZ(z: number): GrowthClassification {
  if (z < -3)  return 'severely_low';
  if (z < -2)  return 'low';
  if (z < -1)  return 'normal_low';
  if (z <=  1) return 'normal';
  if (z <=  2) return 'normal_high';
  if (z <=  3) return 'high';
  return 'severely_high';
}

function computeOne(
  measurement: number | null | undefined,
  table: LmsTable,
  sex: Sex,
  ageMonths: number,
): PercentileResult | null {
  if (measurement == null || !isFinite(measurement) || measurement <= 0) return null;

  const lms = lookupLMS(table[sex], ageMonths);
  if (!lms) return null;

  const z = lmsZScore(measurement, lms);
  const pct = Math.round(normalCDF(z) * 1000) / 10; // one decimal place

  return {
    percentile: pct,
    zScore: Math.round(z * 100) / 100,
    classification: classifyZ(z),
  };
}

// ── Public API ─────────────────────────────────────────────────────────────

export interface GrowthMeasurement {
  weightKg?: number | null;
  heightCm?: number | null;
  headCircumference?: number | null;
  bmi?: number | null;
}

/**
 * Calculate WHO 2006 percentiles for all available growth measurements.
 *
 * @param measurement   The child's measurements at a single point in time.
 * @param sex           Child's sex ('MALE' | 'FEMALE').
 * @param ageMonths     Exact age in months (may be fractional, e.g. 6.5).
 *                      Range: 0–60. Returns null for each metric outside range.
 *
 * @example
 * const pct = calculateGrowthPercentiles(
 *   { weightKg: 9.5, heightCm: 72, headCircumference: 45 },
 *   'MALE', 9,
 * );
 * // pct.weight.percentile → ~50th, pct.weight.classification → 'normal'
 */
export function calculateGrowthPercentiles(
  measurement: GrowthMeasurement,
  sex: Sex,
  ageMonths: number,
): GrowthPercentiles {
  return {
    weight:           computeOne(measurement.weightKg,          WEIGHT_FOR_AGE, sex, ageMonths),
    height:           computeOne(measurement.heightCm,          HEIGHT_FOR_AGE, sex, ageMonths),
    headCircumference:computeOne(measurement.headCircumference, HEAD_FOR_AGE,   sex, ageMonths),
    bmi:              computeOne(measurement.bmi,               BMI_FOR_AGE,    sex, ageMonths),
  };
}

/**
 * Return the measurement value at a given percentile for use in rendering
 * reference curves.  Feed an array of age points and a z-score to get the
 * curve values (percentile 50 = z 0, 97th ≈ z 1.881, 3rd ≈ z -1.881).
 *
 * Useful for building front-end growth chart reference lines without shipping
 * LMS tables to the browser.
 */
export function referenceCurve(
  table: 'weight' | 'height' | 'head' | 'bmi',
  sex: Sex,
  zScore: number,
): Array<{ ageMonths: number; value: number }> {
  const lmsTable =
    table === 'weight' ? WEIGHT_FOR_AGE :
    table === 'height' ? HEIGHT_FOR_AGE :
    table === 'head'   ? HEAD_FOR_AGE   : BMI_FOR_AGE;

  return lmsTable[sex].map((lms, ageMonths) => {
    const [L, M, S] = lms;
    const value =
      Math.abs(L) < 1e-10
        ? M * Math.exp(zScore * S)
        : M * Math.pow(1 + L * S * zScore, 1 / L);
    return { ageMonths, value: Math.round(value * 10) / 10 };
  });
}

/**
 * Convenience: z-score → percentile (rounded to 1 decimal place).
 * Exposed for testing.
 */
export function zScoreToPercentile(z: number): number {
  return Math.round(normalCDF(z) * 1000) / 10;
}
