/**
 * WHO 2006 Child Growth Standards — LMS-based percentile calculator
 *
 * Covers weight-for-age, length/height-for-age, head-circumference-for-age,
 * and BMI-for-age for boys and girls from 0 to 60 months.
 *
 * Reference: WHO Multicentre Growth Reference Study Group (2006).
 *   WHO Child Growth Standards: Length/height-for-age, weight-for-age,
 *   weight-for-length, weight-for-height and body mass index-for-age.
 *   Geneva: World Health Organization.
 *   https://www.who.int/tools/child-growth-standards
 *
 * IMPORTANT FOR PRODUCTION: Verify all LMS values against the official WHO
 * published tables at the URL above before clinical use. The LMS tables
 * embedded here are sourced from the WHO 2006 publication.
 *
 * Method — Box-Cox power transformation (L, M, S):
 *   Z = ((X/M)^L - 1) / (L × S)   when L ≠ 0
 *   Z = ln(X/M) / S                 when L = 0
 *   Percentile = Φ(Z) × 100         where Φ is the standard normal CDF
 *
 * Clinically meaningful z-score limits: |Z| > 3 → use extended curve beyond
 * the 0.13th / 99.87th percentile; the WHO recommends capping at ±3 for
 * interpretation purposes.
 */

// ── Types ──────────────────────────────────────────────────────────────────

export type Sex = 'MALE' | 'FEMALE';

export interface PercentileResult {
  /** Percentile rank (0–100). Null when measurement is outside reference range. */
  percentile: number | null;
  /** Standard deviation score (z-score). */
  zScore: number | null;
  /** Interpretation band for clinical use. */
  classification: GrowthClassification;
}

export type GrowthClassification =
  | 'severely_low'   // Z < -3
  | 'low'            // -3 ≤ Z < -2
  | 'normal_low'     // -2 ≤ Z < -1
  | 'normal'         // -1 ≤ Z ≤ +1
  | 'normal_high'    // +1 < Z ≤ +2
  | 'high'           // +2 < Z ≤ +3
  | 'severely_high'  // Z > +3
  | 'unknown';

export interface GrowthPercentiles {
  weight: PercentileResult | null;
  height: PercentileResult | null;
  headCircumference: PercentileResult | null;
  bmi: PercentileResult | null;
}

/** LMS triplet: [L (lambda), M (mu / median), S (sigma / CV)] */
type LMS = [number, number, number];

