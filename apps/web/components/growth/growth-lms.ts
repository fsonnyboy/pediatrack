// ── LMS math ──────────────────────────────────────────────────────────────────

/**
 * Value at z standard deviations from the median using the LMS method.
 *   X = M × (1 + L×S×z)^(1/L)   when L ≠ 0
 *   X = M × exp(S×z)              when L ≈ 0
 */
function lmsValue([L, M, S]: LMSTriplet, z: number): number {
  if (Math.abs(L) < 1e-8) return M * Math.exp(S * z);
  const inner = 1 + L * S * z;
  if (inner <= 0) return 0;
  return M * Math.pow(inner, 1 / L);
}

/**
 * Z-score for a measurement using the LMS method with WHO extended formula for |z|>3.
 * Clamped to [-5, +5].
 */
function lmsZScore([L, M, S]: LMSTriplet, x: number): number {
  if (x <= 0) return -5;
  let z: number;
  if (Math.abs(L) < 1e-8) {
    z = Math.log(x / M) / S;
  } else {
    z = (Math.pow(x / M, L) - 1) / (L * S);
  }
  // WHO extended z-score beyond ±3 SD
  if (Math.abs(z) > 3) {
    const sign = z > 0 ? 1 : -1;
    const sd3 = lmsValue([L, M, S],  sign * 3);
    const sd2 = lmsValue([L, M, S],  sign * 2);
    const sdDiff = Math.abs(sd3 - sd2);
    z = sign * 3 + (x - sd3) / sdDiff;
  }
  return Math.max(-5, Math.min(5, z));
}

/** Abramowitz & Stegun 26.2.17 — max |error| < 7.5×10⁻⁸. */
function normalCDF(z: number): number {
  const t = 1 / (1 + 0.2316419 * Math.abs(z));
  const poly =
    t * (0.319381530 +
    t * (-0.356563782 +
    t * (1.781477937 +
    t * (-1.821255978 +
    t *   1.330274429))));
  const phi = 1 - (1 / Math.sqrt(2 * Math.PI)) * Math.exp(-0.5 * z * z) * poly;
  return Math.max(0, Math.min(1, z >= 0 ? phi : 1 - phi));
}

/** Linear interpolation for fractional ages. */
function interpolateLMS(table: LMSTriplet[], ageMonths: number): LMSTriplet | null {
  const max = table.length - 1;
  if (ageMonths < 0 || ageMonths > max) return null;
  const lo = Math.floor(ageMonths);
  const hi = Math.min(lo + 1, max);
  const f = ageMonths - lo;
  if (f === 0 || lo === hi) return table[lo];
  return table[lo].map((v, i) => v + f * (table[hi][i] - v)) as LMSTriplet;
}

// ── Public helpers ────────────────────────────────────────────────────────────

/**
 * Build a reference percentile curve for the given metric, sex, and z-score.
 * Returns one point per whole month (0–60).
 */
export function buildReferenceCurve(
  metric: GrowthMetric,
  sex: Sex,
  z: number,
): ReferenceCurvePoint[] {
  const table = LMS_TABLES[metric][sex];
  return table.map(([L, M, S], ageMonths) => ({
    ageMonths,
    value: Math.round(lmsValue([L, M, S], z) * 100) / 100,
  }));
}

/**
 * Compute percentile and z-score for a single measurement.
 * Returns null when ageMonths is outside [0, 60] or value is invalid.
 */
export function computePercentile(
  metric: GrowthMetric,
  sex: Sex,
  ageMonths: number,
  value: number,
): GrowthPercentileResult | null {
  const lms = interpolateLMS(LMS_TABLES[metric][sex], ageMonths);
  if (!lms || value <= 0) return null;
  const z = lmsZScore(lms, value);
  return {
    zScore: Math.round(z * 100) / 100,
    percentile: Math.round(normalCDF(z) * 1000) / 10,
  };
}

export function classifyZScore(z: number): {
  label: string;
  color: string;
  bg: string;
} {
  if (z < -3) return { label: 'Severely Low',  color: '#C0392B', bg: '#FDEDEC' };
  if (z < -2) return { label: 'Low',            color: '#C0392B', bg: '#FDEDEC' };
  if (z < -1) return { label: 'Normal-Low',     color: '#D68910', bg: '#FDEBD0' };
  if (z <=  1) return { label: 'Normal',        color: '#1E8449', bg: '#EAFAF1' };
  if (z <=  2) return { label: 'Normal-High',   color: '#D68910', bg: '#FDEBD0' };
  if (z <=  3) return { label: 'High',          color: '#C0392B', bg: '#FDEDEC' };
  return              { label: 'Severely High', color: '#C0392B', bg: '#FDEDEC' };
}

